const BAD_ENDINGS = new Set('的了是有在个人上下中后前里去来着过们么嘛罢点些')
const BAD_STARTERS = new Set('是有在很挺太更最不没也都就还只光才再要能会几各每某这那哪一')

/** 语法上不像独立词的组合，如“好的”“很大” */
export function isJunkWord(word: string): boolean {
  if (word.length < 2) return true
  if (/^\d+$/.test(word)) return true
  if (word.length === 2 && (BAD_ENDINGS.has(word[1]!) || BAD_STARTERS.has(word[0]!))) return true
  if (word.length === 3 && (/[下点些]$/.test(word) || /[不得]/.test(word))) return true
  return false
}
